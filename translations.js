const translationNodes = Array.from(document.querySelectorAll('[data-i18n], [data-i18n-html], [data-i18n-aria-label]'));
const englishValues = new Map(translationNodes.map(node => [node, {
    text: node.textContent, html: node.innerHTML, label: node.getAttribute('aria-label')
}]));
function setLanguage(language) {
    const lang = language === 'hu' ? 'hu' : 'en';
    translationNodes.forEach(node => {
        const original = englishValues.get(node);
        if (node.dataset.i18n) node.textContent = lang === 'hu' ? hungarianTranslations[node.dataset.i18n] : original.text;
        if (node.dataset.i18nHtml) node.innerHTML = lang === 'hu' ? hungarianTranslations[node.dataset.i18nHtml] : original.html;
        if (node.dataset.i18nAriaLabel) node.setAttribute('aria-label', lang === 'hu' ? hungarianTranslations[node.dataset.i18nAriaLabel] : original.label);
    });
    document.documentElement.lang = lang;
    document.title = lang === 'hu' ? 'TheAdamNew | Minecraft plugin- és szerverfejlesztő' : 'TheAdamNew | Minecraft Plugin and Server Developer';
    document.querySelectorAll('[data-lang]').forEach(button => {
        const active = button.dataset.lang === lang;
        button.classList.toggle('is-active', active);
        button.setAttribute('aria-pressed', String(active));
    });
    try { localStorage.setItem('site-language', lang); } catch {}
}
document.querySelectorAll('[data-lang]').forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.lang)));
